    date_key,
    full_date,
    year,
    quarter,
    month,
    month_name,
    day,
    day_name,
    day_of_week,
    week_of_year,
    is_weekend
)
VALUES (
    0,
    NULL,
    NULL,
    NULL,
    NULL,
    'Unknown',
    NULL,
    'Unknown',
    NULL,
    NULL,
    NULL
);


-- Generate dates from the actual trip data
INSERT INTO warehouse.dim_date (
    date_key,
    full_date,
    year,
    quarter,
    month,
    month_name,
    day,
    day_name,
    day_of_week,
    week_of_year,
    is_weekend
)
SELECT
    (
        EXTRACT(YEAR FROM d)::INTEGER * 10000
        +
        EXTRACT(MONTH FROM d)::INTEGER * 100
        +
        EXTRACT(DAY FROM d)::INTEGER
    ) AS date_key,

    d::DATE AS full_date,

    EXTRACT(YEAR FROM d)::SMALLINT,

    EXTRACT(QUARTER FROM d)::SMALLINT,

    EXTRACT(MONTH FROM d)::SMALLINT,

    TO_CHAR(d, 'Month'),

    EXTRACT(DAY FROM d)::SMALLINT,

    TO_CHAR(d, 'Day'),

    EXTRACT(ISODOW FROM d)::SMALLINT,

    EXTRACT(WEEK FROM d)::SMALLINT,

    CASE
        WHEN EXTRACT(ISODOW FROM d) IN (6, 7)
        THEN TRUE
        ELSE FALSE
    END

FROM generate_series(
    (
        SELECT MIN(pickup_date)
        FROM staging.yellow_taxi_trips
    ),
    (
        SELECT MAX(tpep_dropoff_datetime::DATE)
        FROM staging.yellow_taxi_trips
    ),
    INTERVAL '1 day'
) AS series(d);


