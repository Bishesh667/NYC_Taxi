-- ============================================================
-- 6. FACT TABLE
-- ============================================================

CREATE TABLE warehouse.fact_trips (

    trip_key BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    -- Dimension keys
    pickup_date_key INTEGER NOT NULL,
    dropoff_date_key INTEGER NOT NULL,

    pickup_zone_key INTEGER NOT NULL,
    dropoff_zone_key INTEGER NOT NULL,

    vendor_key INTEGER NOT NULL,
    payment_type_key INTEGER NOT NULL,
    rate_code_key INTEGER NOT NULL,

    -- Trip timestamps
    pickup_datetime TIMESTAMP NOT NULL,
    dropoff_datetime TIMESTAMP NOT NULL,

    -- Trip measurements
    passenger_count NUMERIC(8,2),
    trip_distance NUMERIC(14,3),
    trip_duration_minutes NUMERIC(12,2),

    -- Financial measurements
    fare_amount NUMERIC(12,2),
    extra NUMERIC(12,2),
    mta_tax NUMERIC(12,2),
    tip_amount NUMERIC(12,2),
    tolls_amount NUMERIC(12,2),
    improvement_surcharge NUMERIC(12,2),
    total_amount NUMERIC(12,2),
    congestion_surcharge NUMERIC(12,2),
    airport_fee NUMERIC(12,2),
    cbd_congestion_fee NUMERIC(12,2),

    fare_per_mile NUMERIC(14,4),

    -- Quality flags
    negative_total_amount BOOLEAN,
    zero_distance BOOLEAN,
    zero_duration BOOLEAN,
    zero_passenger_count BOOLEAN,
    missing_passenger_count BOOLEAN,

    -- Derived anomaly flags
    is_financial_anomaly BOOLEAN,
    is_operational_anomaly BOOLEAN

);


-- ============================================================
-- 7. LOAD FACT TABLE
-- ============================================================

INSERT INTO warehouse.fact_trips (

    pickup_date_key,
    dropoff_date_key,

    pickup_zone_key,
    dropoff_zone_key,

    vendor_key,
    payment_type_key,
    rate_code_key,

    pickup_datetime,
    dropoff_datetime,

    passenger_count,
    trip_distance,
    trip_duration_minutes,

    fare_amount,
    extra,
    mta_tax,
    tip_amount,
    tolls_amount,
    improvement_surcharge,
    total_amount,
    congestion_surcharge,
    airport_fee,
    cbd_congestion_fee,

    fare_per_mile,

    negative_total_amount,
    zero_distance,
    zero_duration,
    zero_passenger_count,
    missing_passenger_count,

    is_financial_anomaly,
    is_operational_anomaly

)

SELECT

    -- Pickup date
    COALESCE(
        dd_pick.date_key,
        0
    ),

    -- Dropoff date
    COALESCE(
        dd_drop.date_key,
        0
    ),

    -- Pickup zone
    COALESCE(
        zp.zone_key,
        0
    ),

    -- Dropoff zone
    COALESCE(
        zd.zone_key,
        0
    ),

    -- Vendor
    COALESCE(
        v.vendor_key,
        0
    ),

    -- Payment
    COALESCE(
        p.payment_type_key,
        0
    ),

    -- Rate code
    COALESCE(
        r.rate_code_key,
        0
    ),

    -- Datetimes
    s.tpep_pickup_datetime,
    s.tpep_dropoff_datetime,

    -- Trip metrics
    s.passenger_count,
    s.trip_distance,
    s.trip_duration_minutes,

    -- Financial metrics
    s.fare_amount,
    s.extra,
    s.mta_tax,
    s.tip_amount,
    s.tolls_amount,
    s.improvement_surcharge,
    s.total_amount,
    s.congestion_surcharge,
    s.airport_fee,
    s.cbd_congestion_fee,

    s.fare_per_mile,

    -- Quality flags
    s.negative_total_amount,
    s.zero_distance,
    s.zero_duration,
    s.zero_passenger_count,
    s.missing_passenger_count,

    -- Financial anomaly
    s.negative_total_amount,

    -- Operational anomaly
    (
        s.zero_distance
        OR
        s.zero_duration
        OR
        s.zero_passenger_count
        OR
        s.missing_passenger_count
    )

FROM staging.yellow_taxi_trips s

LEFT JOIN warehouse.dim_date dd_pick
    ON dd_pick.full_date = s.pickup_date

LEFT JOIN warehouse.dim_date dd_drop
    ON dd_drop.full_date =
       s.tpep_dropoff_datetime::DATE

LEFT JOIN warehouse.dim_zone zp
    ON zp.location_id = s.pulocation_id

LEFT JOIN warehouse.dim_zone zd
    ON zd.location_id = s.dolocation_id

LEFT JOIN warehouse.dim_vendor v
    ON v.vendor_id = s.vendor_id

LEFT JOIN warehouse.dim_payment_type p
    ON p.payment_type_code = s.payment_type

LEFT JOIN warehouse.dim_rate_code r
    ON r.rate_code_id = s.ratecode_id

WHERE s.is_valid_record = TRUE;


