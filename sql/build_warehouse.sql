-- ============================================================
-- 1. DATE DIMENSION
-- ============================================================

CREATE TABLE warehouse.dim_date (
    date_key INTEGER PRIMARY KEY,
    full_date DATE UNIQUE,
    year SMALLINT,
    quarter SMALLINT,
    month SMALLINT,
    month_name VARCHAR(20),
    day SMALLINT,
    day_name VARCHAR(20),
    day_of_week SMALLINT,
    week_of_year SMALLINT,
    is_weekend BOOLEAN
);


-- Unknown date row
